package day1;

public class ArithmeticOperator {

	public static void main(String[] args) {
		int a = 10;
		int b = 20;
		
		System.out.println(a+b + " : + operator");
		System.out.println(a-b + " : - operator");
		System.out.println(a*b + " : * operator");
		System.out.println(b/a + " : / operator");
		System.out.println(a%b + " : % operator");

	}

}
